#!/usr/bin/env python3
"""Generates watch/src/c/sounds.c: short PCM samples (16 kHz, 16 bit, mono).

Why samples instead of speaker_play_tone(): a tone starts and stops hard, which
clicks, and full-scale waveforms distort the small speaker of the Pebble Time 2.
These samples have a soft attack/decay and stay at 40 % of full scale. The watch
pitch-shifts them per note (speaker_play_tracks), so one sample covers every pitch.

Run: python3 tools/make_sounds.py   (from the watch/ directory)
"""
import math
import random
import os

RATE = 16000
PEAK = 0.40  # fraction of full scale; the speaker distorts near 100 %


def beep():
    # 880 Hz sine (MIDI 81), 70 ms: 6 ms raised-cosine attack, exponential decay
    n = int(RATE * 0.070)
    attack = int(RATE * 0.006)
    out = []
    for i in range(n):
        if i < attack:
            env = 0.5 - 0.5 * math.cos(math.pi * i / attack)
        else:
            t = (i - attack) / (n - attack)
            env = math.exp(-3.2 * t) * (1 - t) ** 0.5  # reaches exactly 0 at the end
        out.append(env * math.sin(2 * math.pi * 880 * i / RATE))
    return out


def click():
    # Geiger-counter tick: 9 ms of filtered noise with a fast decay
    random.seed(7)
    n = int(RATE * 0.009)
    out, lp = [], 0.0
    for i in range(n):
        lp += 0.45 * (random.uniform(-1, 1) - lp)  # soften the hiss
        env = math.exp(-i / (RATE * 0.0018))
        if i < 16:
            env *= i / 16  # 1 ms fade-in, no step at the start
        out.append(env * lp * 2.2)
    out[-1] = 0.0
    return out


def to_c(name, samples):
    mx = max(abs(s) for s in samples) or 1
    vals = [int(round(s / mx * PEAK * 32767)) for s in samples]
    lines = []
    for i in range(0, len(vals), 12):
        lines.append("  " + ", ".join(str(v) for v in vals[i:i + 12]) + ",")
    return f"const int16_t {name}[{len(vals)}] = {{\n" + "\n".join(lines) + "\n};\n", len(vals)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    src = os.path.join(here, "..", "src", "c")
    b, nb = to_c("SOUND_BEEP", beep())
    c, nc = to_c("SOUND_CLICK", click())
    with open(os.path.join(src, "sounds.c"), "w") as f:
        f.write("// Generated by tools/make_sounds.py - do not edit.\n#include \"sounds.h\"\n\n" + b + "\n" + c)
    with open(os.path.join(src, "sounds.h"), "w") as f:
        f.write(
            "// Generated by tools/make_sounds.py - do not edit.\n#pragma once\n#include <pebble.h>\n\n"
            f"#define SOUND_BEEP_LEN {nb}\n#define SOUND_BEEP_MIDI 81  // 880 Hz\n"
            f"extern const int16_t SOUND_BEEP[SOUND_BEEP_LEN];\n\n"
            f"#define SOUND_CLICK_LEN {nc}\n#define SOUND_CLICK_MIDI 72\n"
            f"extern const int16_t SOUND_CLICK[SOUND_CLICK_LEN];\n"
        )
    print(f"beep {nb} samples, click {nc} samples")


if __name__ == "__main__":
    main()
