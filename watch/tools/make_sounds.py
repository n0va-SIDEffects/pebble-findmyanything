#!/usr/bin/env python3
"""Generates watch/src/c/sounds.c/.h: tables for the search sound (16 kHz, 16 bit, mono).

The watch synthesises the beep itself into one PCM stream that stays open for
the whole search (src/c/audio_pump.c). Why not speaker_play_tracks():
- The firmware powers the audio codec and amplifier up and down for every
  single sound on the Time 2 (speaker standby 0 ms on obelix). Restarting the
  audio path for every beep is what crackled.
- It re-pitches samples with nearest-neighbour stepping (no interpolation),
  which adds rough overtones.

Tables:
- SINE_TABLE: one sine period, 256 steps + 1 guard entry for interpolation.
- BEEP_ENV: amplitude envelope of one beep in Q15, peak already included.
  Raised-cosine attack and release: starts and ends at exactly 0 with a flat
  slope, so the beep never steps.
- SOUND_CLICK: Geiger-counter tick, played as is (no re-pitching).

Run: python3 tools/make_sounds.py   (from the watch/ directory)
"""
import math
import os
import random

RATE = 16000
PEAK = 0.40          # fraction of full scale; the small speaker distorts near 100 %
BEEP_MS = 60
ATTACK_MS = 6
RELEASE_MS = 34


def sine_table():
    return [int(round(32767 * math.sin(2 * math.pi * i / 256))) for i in range(257)]


def beep_env():
    n = RATE * BEEP_MS // 1000
    a = RATE * ATTACK_MS // 1000
    r = RATE * RELEASE_MS // 1000
    out = []
    for i in range(n):
        if i < a:
            e = 0.5 - 0.5 * math.cos(math.pi * i / a)
        elif i >= n - r:
            k = (n - 1 - i) / (r - 1)          # 1 -> 0
            e = 0.5 - 0.5 * math.cos(math.pi * k)
        else:
            e = 1.0
        out.append(int(round(e * PEAK * 32767)))
    out[0] = 0
    out[-1] = 0
    return out


def click():
    # Geiger-counter tick: 9 ms of filtered noise with a fast decay
    random.seed(7)
    n = int(RATE * 0.009)
    out, lp = [], 0.0
    for i in range(n):
        lp += 0.45 * (random.uniform(-1, 1) - lp)  # soften the hiss
        env = math.exp(-i / (RATE * 0.0018))
        if i < 16:
            env *= i / 16  # 1 ms fade-in, no step at the start
        out.append(env * lp)
    mx = max(abs(s) for s in out)
    vals = [int(round(s / mx * PEAK * 32767)) for s in out]
    vals[-1] = 0
    return vals


def c_array(ctype, name, vals):
    lines = ["  " + ", ".join(str(v) for v in vals[i:i + 12]) + "," for i in range(0, len(vals), 12)]
    return f"const {ctype} {name}[{len(vals)}] = {{\n" + "\n".join(lines) + "\n};\n"


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    src = os.path.join(here, "..", "src", "c")
    sine, env, clk = sine_table(), beep_env(), click()
    with open(os.path.join(src, "sounds.c"), "w") as f:
        f.write("// Generated by tools/make_sounds.py - do not edit.\n#include \"sounds.h\"\n\n")
        f.write(c_array("int16_t", "SINE_TABLE", sine) + "\n")
        f.write(c_array("uint16_t", "BEEP_ENV", env) + "\n")
        f.write(c_array("int16_t", "SOUND_CLICK", clk))
    with open(os.path.join(src, "sounds.h"), "w") as f:
        f.write(
            "// Generated by tools/make_sounds.py - do not edit.\n#pragma once\n#include <pebble.h>\n\n"
            "// One sine period in 256 steps, plus a guard entry (= entry 0) for interpolation\n"
            "extern const int16_t SINE_TABLE[257];\n\n"
            f"// Beep envelope, Q15, peak {PEAK:.0%} of full scale included\n"
            f"#define BEEP_ENV_LEN {len(env)}\n"
            "extern const uint16_t BEEP_ENV[BEEP_ENV_LEN];\n\n"
            f"#define SOUND_CLICK_LEN {len(clk)}\n"
            "extern const int16_t SOUND_CLICK[SOUND_CLICK_LEN];\n"
        )
    print(f"sine 257, beep envelope {len(env)} samples, click {len(clk)} samples")


if __name__ == "__main__":
    main()
